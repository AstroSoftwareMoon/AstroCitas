// Captura fotogramas del flujo "crear cita en 3 toques" para el GIF del README (montado con scripts/make-gif.py).
import { chromium } from 'playwright';
import { mkdirSync } from 'node:fs';
const dir = process.argv[2] ?? 'docs/screenshots/frames';
mkdirSync(dir, { recursive: true });
const BASE = process.env.BASE_URL ?? 'http://localhost:4173';
const browser = await chromium.launch({ args: ['--lang=es-ES'] });
const ctx = await browser.newContext({ viewport: { width: 1280, height: 800 }, deviceScaleFactor: 1, locale: 'es-ES', timezoneId: 'Europe/Madrid' });
const page = await ctx.newPage();
await page.clock.setFixedTime(new Date('2026-11-19T11:40:00+01:00'));
let n = 0;
const shot = async (ms = 1200) => page.screenshot({ path: `${dir}/${String(n++).padStart(2, '0')}-${ms}.png` });
await page.goto(BASE);
await page.waitForTimeout(300);
await shot(1400);
await page.getByTestId('mode-local').click();
await page.getByTestId('onb-name').pressSequentially('Estudio Luna', { delay: 10 });
await page.getByRole('button', { name: 'Peluquería' }).click();
await page.getByPlaceholder('Tu nombre').fill('Marta');
await shot(1600);
await page.getByTestId('onb-start').click();
await page.getByTestId('appt').first().waitFor({ timeout: 20000 });
await page.getByRole('tab', { name: 'Día' }).click();
await page.waitForTimeout(300);
await shot(1600);
await page.getByTestId('new-appt').click();
const dlg = page.getByRole('dialog');
await page.waitForTimeout(250);
await shot(1000);
await dlg.getByRole('button', { name: /^Corte hombre/ }).click();
await dlg.getByRole('button', { name: /Ana$/ }).click();
await page.waitForTimeout(150);
await shot(1100);
await dlg.getByTestId('slots').getByRole('button').nth(2).click();
await shot(1000);
await dlg.getByTestId('client-search').fill('Sergio');
await dlg.getByTestId('client-create').click();
await dlg.getByPlaceholder('Teléfono').fill('+34 611 222 333');
await shot(1200);
await dlg.getByTestId('appt-save').click();
await page.waitForTimeout(400);
await shot(2200);
await page.getByRole('tab', { name: 'Semana' }).click();
await page.waitForTimeout(400);
await shot(2200);
await browser.close();
